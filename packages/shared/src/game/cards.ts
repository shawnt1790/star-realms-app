import type { CardDef, Effect, Faction } from "./types.js";

const trade = (amount: number): Effect => ({ kind: "trade", amount });
const combat = (amount: number): Effect => ({ kind: "combat", amount });
const authority = (amount: number): Effect => ({ kind: "authority", amount });
const draw = (amount = 1): Effect => ({ kind: "draw", amount });
const oppDiscard = (amount = 1): Effect => ({ kind: "opponent_discard", amount });
const scrapHandOrDiscard = (max = 1): Effect => ({ kind: "scrap_hand_or_discard", max });
const scrapTradeRow: Effect = { kind: "scrap_trade_row" };
const destroyBase: Effect = { kind: "destroy_base" };
const choose = (...options: { label: string; effects: Effect[] }[]): Effect => ({
  kind: "choose",
  options,
});

