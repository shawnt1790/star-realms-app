export const ALL_CARDS: CardDef[] = [
  ...starters,
  ...tradeFederation,
  ...blob,
  ...machineCult,
  ...starEmpire,
];

export const CARD_INDEX: Record<string, CardDef> = Object.fromEntries(
  ALL_CARDS.map((c) => [c.id, c]),
);

export function getCardDef(defId: string): CardDef {
  const def = CARD_INDEX[defId];
  if (!def) throw new Error(`Unknown card def: ${defId}`);
  return def;
}

/** Definitions that make up the 80-card trade deck (with counts). */
export const TRADE_DECK_DEFS: CardDef[] = ALL_CARDS.filter((c) => c.count > 0);

